uint8_t font5x7_row(char c, int row)
{
    if (c < 0x20 || c > 0x7E || row < 0 || row >= 7)
        return 0;
    const char *s = GLYPHS[c - 0x20][row];
    uint8_t bits = 0;
    for (int i = 0; i < 5; i++)
        if (s[i] == '#')
            bits |= (uint8_t)(0x10 >> i);   /* bit 4 = 最左邊 */
    return bits;
}
